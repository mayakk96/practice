CREATE TABLE event_outbox (
    id UUID PRIMARY KEY,
    sequence_number BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE,
    case_id UUID NOT NULL,
    event_type VARCHAR(80) NOT NULL,
    event_json VARCHAR(12000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_failure VARCHAR(40)
);

-- Dispatch scans unpublished events by sequence; the second index enforces per-case ordering efficiently.
CREATE INDEX idx_outbox_pending ON event_outbox (published_at, next_attempt_at, sequence_number);
CREATE INDEX idx_outbox_case_order ON event_outbox (case_id, published_at, sequence_number);

CREATE TABLE onboarding_audit_event (
    event_id UUID PRIMARY KEY,
    case_id UUID NOT NULL,
    event_type VARCHAR(80) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    payload_hash VARCHAR(64) NOT NULL
);

CREATE INDEX idx_audit_case_time ON onboarding_audit_event (case_id, occurred_at);
